#!/usr/bin/env node
/**
 * Bundle cleaned 13 universal software engineering skills (7 linked core + 6 full discovery/PRD)
 * and stage rules into frontend/src/data/bundledAssets.ts for zero-network single-file execution.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.resolve(__dirname, '..');
const devStageRoot = path.resolve(frontendRoot, '..', '..');
const projectRoot = path.resolve(devStageRoot, '..');
const designStageRoot = path.resolve(projectRoot, '02-product-design-产品设计阶段');
const adaptedSkillsRoot = path.resolve(devStageRoot, '.agents', 'skills');

const CORE_LINKED_SKILLS = [
  'build-fde-project',
  'classify-project-data',
  'product-spec',
  'feature-spec-planning',
  'project-evals',
  'maintain-project',
  'deliver-project',
];

const FULL_EXTRA_SKILLS = [
  'product-prd',
  'prepare-requirement-materials',
  'normalize-project-requirements',
  'review-project-requirements',
  'build-frontend-prototype',
  'playground',
];

const TEXT_EXTENSIONS = new Set(['.md', '.py', '.yaml', '.yml', '.json', '.html', '.txt', '.csv']);

function scrubContent(text) {
  return text
    .replace(/@FUF\s*独家研发/g, '工程研发团队')
    .replace(/FF\s*-\s*<正式产品名>/g, '<正式产品名>')
    .replace(/~\/\.config\/skyforge\/credentials\.yaml/g, '受保护的本地凭证配置')
    .replace(/\/Users\/muyu\/MuYuKnowledge/g, '团队或个人知识库目录');
}

function collectSkillFiles(skillDir) {
  const files = {};
  function walk(currentDir) {
    for (const entry of fs.readdirSync(currentDir, { withFileTypes: true })) {
      if (entry.name.startsWith('.')) continue;
      if (
        entry.isDirectory() &&
        (entry.name === 'tests' ||
          entry.name === 'brand' ||
          entry.name === 'illustrations' ||
          entry.name === '__pycache__')
      ) {
        continue;
      }
      const fullPath = path.join(currentDir, entry.name);
      const relPath = path.relative(skillDir, fullPath).split(path.sep).join('/');
      if (entry.isDirectory()) {
        walk(fullPath);
      } else if (entry.isFile()) {
        if (
          entry.name.startsWith('test_') ||
          entry.name.endsWith('.patch') ||
          entry.name.endsWith('.cjs')
        ) {
          continue;
        }
        const ext = path.extname(entry.name).toLowerCase();
        if (TEXT_EXTENSIONS.has(ext) || entry.name === 'UPSTREAM-LICENSE') {
          const raw = fs.readFileSync(fullPath, 'utf-8');
          files[relPath] = scrubContent(raw);
        }
      }
    }
  }
  if (fs.existsSync(skillDir)) {
    walk(skillDir);
  }
  return files;
}

const bundledSkills = {};

for (const name of CORE_LINKED_SKILLS) {
  const dir = path.join(adaptedSkillsRoot, name);
  bundledSkills[name] = {
    name,
    category: 'core',
    files: collectSkillFiles(dir),
  };
}

for (const name of FULL_EXTRA_SKILLS) {
  const dir = path.join(adaptedSkillsRoot, name);
  bundledSkills[name] = {
    name,
    category: 'discovery',
    files: collectSkillFiles(dir),
  };
}

const engineeringPrinciplesPath = path.join(
  devStageRoot,
  '.agents',
  'rules',
  'engineering-principles.md'
);
const designPrinciplesPath = path.join(
  designStageRoot,
  '.agents',
  'rules',
  'design-principles.md'
);
const codingDisciplinePath = path.join(
  devStageRoot,
  '.agents',
  'rules',
  'coding-discipline.md'
);

const bundledTemplates = {
  engineeringPrinciples: fs.readFileSync(engineeringPrinciplesPath, 'utf-8'),
  designPrinciples: fs.readFileSync(designPrinciplesPath, 'utf-8'),
  codingDiscipline: fs.readFileSync(codingDisciplinePath, 'utf-8'),
};

const contextTemplatesDir = path.join(frontendRoot, 'templates', 'context');
const bundledContextTemplates = fs.existsSync(contextTemplatesDir)
  ? fs
      .readdirSync(contextTemplatesDir)
      .filter((name) => name.endsWith('.md'))
      .sort()
      .map((filename) => ({
        filename,
        content: fs.readFileSync(path.join(contextTemplatesDir, filename), 'utf-8'),
      }))
  : [];

const outputTemplatesDir = path.join(frontendRoot, 'templates', 'output');
const bundledOutputTemplates = fs.existsSync(outputTemplatesDir)
  ? fs
      .readdirSync(outputTemplatesDir)
      .filter((name) => name.endsWith('.md'))
      .sort()
      .map((filename) => ({
        filename,
        content: fs.readFileSync(path.join(outputTemplatesDir, filename), 'utf-8'),
      }))
  : [];

const outDir = path.join(frontendRoot, 'src', 'data');
fs.mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, 'bundledAssets.ts');

const tsSource = `// AUTO-GENERATED BY scripts/bundle_skills_data.mjs — DO NOT EDIT MANUALLY
export interface BundledSkillEntry {
  name: string;
  category: 'core' | 'discovery';
  files: Record<string, string>;
}

export interface BundledTemplateFile {
  filename: string;
  content: string;
}

export const BUNDLED_SKILLS: Record<string, BundledSkillEntry> = ${JSON.stringify(bundledSkills, null, 2)};

export const BUNDLED_TEMPLATES = ${JSON.stringify(bundledTemplates, null, 2)} as const;

export const BUNDLED_CONTEXT_TEMPLATES: BundledTemplateFile[] = ${JSON.stringify(bundledContextTemplates, null, 2)};

export const BUNDLED_OUTPUT_TEMPLATES: BundledTemplateFile[] = ${JSON.stringify(bundledOutputTemplates, null, 2)};
`;

fs.writeFileSync(outFile, tsSource, 'utf-8');
console.log(
  `[bundle_skills_data] Bundled ${Object.keys(bundledSkills).length} skills, ${Object.keys(bundledTemplates).length} rules, ${bundledContextTemplates.length} context templates, and ${bundledOutputTemplates.length} output templates into src/data/bundledAssets.ts`
);
